import type { TDocumentDefinitions, Content, ContentColumns, Column } from 'pdfmake/interfaces'
import { formatAmount, calculateTotalsBigInt } from '@/shared/lib/amount-utils'
import { formatDateUTC } from '@/shared/lib/date-time'
import { getNetworkName } from '@/entities/network'
import { truncateAddress } from '@/shared/lib/validation'
import type { PartialInvoice } from '@/shared/lib/invoice-types'
import type { PdfExportOptions } from '../model/types'

const COLORS = {
  text: '#27272a',
  muted: '#71717a',
  border: '#d4d4d8',
  light: '#a1a1aa',
  brand: '#7c3aed',
} as const

/**
 * Build pdfmake document definition from invoice data.
 * Pure function — no side effects, fully testable.
 */
export function buildDocument(
  data: PartialInvoice,
  options: PdfExportOptions
): TDocumentDefinitions {
  const decimals = data.decimals ?? 6
  const currency = data.currency ?? ''
  const invoiceId = data.invoiceId ?? 'DRAFT'
  const networkName = data.networkId ? getNetworkName(data.networkId) : ''
  const totals = computeTotals(data, decimals)

  return {
    pageSize: 'A4',
    pageOrientation: 'portrait',
    pageMargins: [40, 40, 40, 60] as [number, number, number, number],
    watermark: options.status
      ? { text: options.status.toUpperCase(), opacity: 0.06, bold: true, fontSize: 72, color: COLORS.muted }
      : undefined,
    content: [
      buildHeader(invoiceId, data, networkName, currency, options),
      separator(),
      buildParties(data),
      separator(),
      buildLineItemsTable(data.items, decimals),
      buildTotalsSection(totals, currency, data.tax, data.discount),
      ...buildFooterContent(data.notes, options.txHash),
    ],
    defaultStyle: {
      font: 'Roboto',
      fontSize: 10,
      color: COLORS.text,
    },
    styles: {
      header: { fontSize: 18, bold: true, color: COLORS.brand },
      subheader: { fontSize: 12, bold: true },
      meta: { fontSize: 9, color: COLORS.muted },
      sectionLabel: { fontSize: 8, color: COLORS.muted, bold: true },
      partyName: { fontSize: 11, bold: true },
      partyDetail: { fontSize: 9, color: COLORS.muted },
      tableHeader: { fontSize: 9, bold: true, color: COLORS.muted },
    },
    footer: {
      text: 'Generated by VoidPay \u00B7 voidpay.xyz',
      alignment: 'center',
      fontSize: 8,
      color: COLORS.light,
      margin: [0, 20, 0, 0],
    },
  }
}

/**
 * Generate PDF filename from invoice data.
 * Format: voidpay-{invoiceId}-{total}-{currency}.pdf
 */
export function buildFilename(data: PartialInvoice): string {
  const id = data.invoiceId
  const currency = data.currency
  const decimals = data.decimals ?? 6

  if (!id && !data.total) return 'voidpay-invoice.pdf'

  const totalStr = data.total
    ? formatAmount(data.total, decimals, { useGrouping: false })
    : undefined

  const parts = ['voidpay']
  if (id) parts.push(id)
  if (totalStr) parts.push(totalStr)
  if (currency) parts.push(currency)

  return parts.length > 1 ? `${parts.join('-')}.pdf` : 'voidpay-invoice.pdf'
}

// ── Internal helpers ──────────────────────────────────────────────

function separator(): Content {
  return {
    canvas: [{ type: 'line', x1: 0, y1: 0, x2: 515, y2: 0, lineWidth: 0.5, lineColor: COLORS.border }],
    margin: [0, 12, 0, 12],
  }
}

function buildHeader(
  invoiceId: string,
  data: PartialInvoice,
  networkName: string,
  currency: string,
  options: PdfExportOptions
): ContentColumns {
  const issuedDate = data.issuedAt ? formatDateUTC(data.issuedAt) : '\u2014'
  const dueDate = data.dueAt ? formatDateUTC(data.dueAt) : '\u2014'

  const headerStack: Content[] = [
    { text: 'VOIDPAY INVOICE', style: 'header' },
    { text: `Invoice: ${invoiceId}`, style: 'subheader', margin: [0, 8, 0, 0] },
    { text: `Issued: ${issuedDate}    Due: ${dueDate}`, style: 'meta', margin: [0, 4, 0, 0] },
  ]

  if (networkName || currency) {
    const metaParts: string[] = []
    if (networkName) metaParts.push(`Network: ${networkName}`)
    if (currency) metaParts.push(`Currency: ${currency}`)
    headerStack.push({ text: metaParts.join('    '), style: 'meta', margin: [0, 2, 0, 0] })
  }

  const columns: Column[] = [{ stack: headerStack, width: '*' }]

  if (options.invoiceUrl) {
    columns.push({ qr: options.invoiceUrl, fit: 80, alignment: 'right', width: 80 } as Column)
  }

  return { columns }
}

function buildParties(data: PartialInvoice): ContentColumns {
  return {
    columns: [
      {
        stack: [
          { text: 'From', style: 'sectionLabel' },
          { text: data.from?.name ?? '\u2014', style: 'partyName', margin: [0, 4, 0, 0] },
          ...(data.from?.walletAddress
            ? [{ text: truncateAddress(String(data.from.walletAddress)), style: 'partyDetail' } as Content]
            : []),
          ...(data.from?.email ? [{ text: String(data.from.email), style: 'partyDetail' } as Content] : []),
        ],
        width: '50%',
      },
      {
        stack: [
          { text: 'Bill To', style: 'sectionLabel' },
          { text: data.client?.name ?? '\u2014', style: 'partyName', margin: [0, 4, 0, 0] },
          ...(data.client?.walletAddress
            ? [{ text: truncateAddress(String(data.client.walletAddress)), style: 'partyDetail' } as Content]
            : []),
          ...(data.client?.email ? [{ text: String(data.client.email), style: 'partyDetail' } as Content] : []),
        ],
        width: '50%',
      },
    ],
  }
}

function buildLineItemsTable(
  items: PartialInvoice['items'],
  decimals: number
): Content {
  const safeItems = (items ?? []) as Array<{ description?: string; quantity?: number; rate?: string }>

  const headerRow = [
    { text: '#', style: 'tableHeader', alignment: 'center' as const },
    { text: 'Description', style: 'tableHeader' },
    { text: 'Qty', style: 'tableHeader', alignment: 'right' as const },
    { text: 'Rate', style: 'tableHeader', alignment: 'right' as const },
    { text: 'Amount', style: 'tableHeader', alignment: 'right' as const },
  ]

  const dataRows = safeItems.map((item, i) => {
    const qty = item.quantity ?? 0
    const rate = item.rate ?? '0'
    const lineTotal = computeLineTotal(qty, rate, decimals)
    return [
      { text: `${i + 1}`, alignment: 'center' as const },
      { text: item.description ?? '' },
      { text: `${qty}`, alignment: 'right' as const },
      { text: formatAmount(rate, decimals), alignment: 'right' as const },
      { text: formatAmount(lineTotal, decimals), alignment: 'right' as const },
    ]
  })

  if (dataRows.length === 0) {
    dataRows.push([
      { text: '', alignment: 'center' as const },
      { text: 'No items' },
      { text: '', alignment: 'right' as const },
      { text: '', alignment: 'right' as const },
      { text: '', alignment: 'right' as const },
    ])
  }

  return {
    table: {
      headerRows: 1,
      widths: [25, '*', 35, 80, 80],
      body: [headerRow, ...dataRows],
    },
    layout: {
      hLineWidth: (i: number, node: { table: { body: unknown[][] } }) =>
        i === 0 || i === 1 || i === node.table.body.length ? 0.5 : 0.2,
      vLineWidth: () => 0,
      hLineColor: () => COLORS.border,
      paddingTop: () => 6,
      paddingBottom: () => 6,
    },
  }
}

interface FormattedTotals {
  subtotal: string
  taxAmount: string
  discountAmount: string
  total: string
  magicDust: string | null
}

function buildTotalsSection(
  totals: FormattedTotals,
  currency: string,
  tax: string | undefined,
  discount: string | undefined
): Content {
  const rows: Content[][] = [
    [{ text: 'Subtotal:', alignment: 'right' }, { text: totals.subtotal, alignment: 'right' }],
  ]

  if (tax && tax !== '0') {
    rows.push([
      { text: `Tax (${tax}%):`, alignment: 'right' },
      { text: totals.taxAmount, alignment: 'right' },
    ])
  }

  if (discount && discount !== '0') {
    rows.push([
      { text: `Discount (${discount}%):`, alignment: 'right' },
      { text: `-${totals.discountAmount}`, alignment: 'right' },
    ])
  }

  rows.push([
    { text: `Total (${currency}):`, bold: true, fontSize: 12, alignment: 'right' },
    { text: totals.total, bold: true, fontSize: 12, alignment: 'right' },
  ])

  if (totals.magicDust) {
    rows.push([
      { text: 'Magic Dust:', alignment: 'right', fontSize: 8, color: COLORS.muted },
      { text: `+${totals.magicDust}`, alignment: 'right', fontSize: 8, color: COLORS.muted },
    ])
  }

  return {
    margin: [0, 12, 0, 0] as [number, number, number, number],
    columns: [
      { text: '', width: '*' },
      {
        width: 220,
        table: { widths: ['*', 90], body: rows },
        layout: 'noBorders',
      },
    ],
  }
}

function buildFooterContent(notes: string | undefined, txHash: string | undefined): Content[] {
  if (!notes && !txHash) return []

  const content: Content[] = [separator()]
  if (notes) {
    content.push({ text: `Notes: ${notes}`, fontSize: 9, color: COLORS.muted, italics: true })
  }
  if (txHash) {
    content.push({
      text: `Tx: ${txHash}`,
      fontSize: 9,
      color: COLORS.muted,
      margin: [0, notes ? 4 : 0, 0, 0] as [number, number, number, number],
    })
  }
  return content
}

function computeLineTotal(qty: number, rate: string, decimals: number): string {
  try {
    const scale = 10n ** BigInt(decimals)
    const qtyScaled = BigInt(Math.round(qty * Number(scale)))
    return ((qtyScaled * BigInt(rate || '0')) / scale).toString()
  } catch {
    return '0'
  }
}

function computeTotals(data: PartialInvoice, decimals: number): FormattedTotals {
  const items = (data.items ?? []) as Array<{ quantity?: number; rate?: string }>

  if (data.total) {
    const result = calculateTotalsBigInt(
      items.map((item) => ({ quantity: item.quantity ?? 0, rate: item.rate ?? '0' })),
      { tax: data.tax, discount: data.discount, decimals }
    )

    const displayTotal = data.magicDust
      ? (BigInt(data.total) - BigInt(data.magicDust)).toString()
      : data.total

    return {
      subtotal: formatAmount(result.subtotal, decimals),
      taxAmount: formatAmount(result.taxAmount, decimals),
      discountAmount: formatAmount(result.discountAmount, decimals),
      total: formatAmount(displayTotal, decimals),
      magicDust: data.magicDust ? formatAmount(data.magicDust, decimals, { displayDecimals: 6 }) : null,
    }
  }

  const result = calculateTotalsBigInt(
    items.map((item) => ({ quantity: item.quantity ?? 0, rate: item.rate ?? '0' })),
    { tax: data.tax, discount: data.discount, decimals }
  )

  return {
    subtotal: formatAmount(result.subtotal, decimals),
    taxAmount: formatAmount(result.taxAmount, decimals),
    discountAmount: formatAmount(result.discountAmount, decimals),
    total: formatAmount(result.total, decimals),
    magicDust: data.magicDust ? formatAmount(data.magicDust, decimals, { displayDecimals: 6 }) : null,
  }
}
