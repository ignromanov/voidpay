/**
 * Build pdfmake document definition from invoice data.
 * Layout closely matches the web InvoicePaper component.
 */
export function buildDocument(
  data: PartialInvoice,
  options: PdfExportOptions
): TDocumentDefinitions {
  const decimals = data.decimals ?? 6
  const currency = data.currency ?? ''
  const invoiceId = data.invoiceId ?? 'DRAFT'
  const networkName = data.networkId ? getNetworkName(data.networkId) : ''
  const totals = computeTotals(data, decimals)

  return {
    pageSize: 'A4',
    pageOrientation: 'portrait',
    pageMargins: [50, 50, 50, 60] as [number, number, number, number],
    watermark: options.status && options.status !== 'pending'
      ? {
          text: options.status === 'paid' && options.paidAt
            ? `${options.status.toUpperCase()}\n${formatDateUTC(options.paidAt)}`
            : options.status.toUpperCase(),
          opacity: 0.10, bold: true, fontSize: 72, color: COLORS.muted,
        }
      : undefined,
    content: [
      buildHeader(invoiceId, data, options),
      thickRule(),
      buildParties(data),
      buildLineItems(data.items, decimals),
      thickRule(),
      buildBottomSection(totals, currency, data, networkName, options),
      dashedRule(),
      buildContentFooter(data.notes),
    ],
    defaultStyle: {
      font: 'Roboto',
      fontSize: 10,
      color: COLORS.text,
      lineHeight: 1.3,
    },
    footer: {
      text: [
        { text: 'Generated by VoidPay \u00B7 ', color: COLORS.muted },
        { text: 'voidpay.xyz', color: COLORS.muted, link: APP_URLS.base },
      ],
      alignment: 'center',
      fontSize: 7.5,
      margin: [0, 15, 0, 0],
    },
  }
}

/**
 * Generate PDF filename from invoice data.
 * Format: voidpay-{invoiceId}-{total}-{currency}.pdf
 */
export function buildFilename(data: PartialInvoice): string {
  const id = data.invoiceId
  const currency = data.currency
  const decimals = data.decimals ?? 6

  if (!id && !data.total) return 'voidpay-invoice.pdf'

  const rawTotal = data.total ? getDisplayTotal(data.total, data.magicDust) : undefined
  const totalStr = rawTotal
    ? formatAmount(rawTotal, decimals, { useGrouping: false })
    : undefined

  const parts = ['voidpay']
  if (id) parts.push(id)
  if (totalStr) parts.push(totalStr)
  if (currency) parts.push(currency)

  return parts.length > 1 ? `${parts.join('-')}.pdf` : 'voidpay-invoice.pdf'
}

