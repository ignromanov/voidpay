/** Thick dark rule matching web border-b-2 border-zinc-700 */
function thickRule(): Content {
  return {
    canvas: [{ type: 'line', x1: 0, y1: 0, x2: CONTENT_WIDTH, y2: 0, lineWidth: 1.5, lineColor: COLORS.borderThick }],
    margin: [0, 12, 0, 12],
  }
}

/** Dashed rule matching web border-t border-dashed border-zinc-300 */
function dashedRule(): Content {
  return {
    canvas: [{
      type: 'line', x1: 0, y1: 0, x2: CONTENT_WIDTH, y2: 0,
      lineWidth: 0.5, lineColor: COLORS.borderDashed,
      dash: { length: 4, space: 3 },
    }],
    margin: [0, 10, 0, 10],
  }
}

// ── Header (matches PaperHeader.tsx) ────────────────────────

function buildHeader(
  invoiceId: string,
  data: PartialInvoice,
  options: PdfExportOptions
): ContentColumns {
  const issuedDate = data.issuedAt ? formatDateUTC(data.issuedAt) : '\u2014'
  const dueDate = data.dueAt ? formatDateUTC(data.dueAt) : '\u2014'
  const isDraft = invoiceId === 'DRAFT'

  // Left: "INVOICE #ID" matching web text-4xl font-black uppercase
  const titleLine: Content = {
    text: [
      { text: 'INVOICE ', fontSize: 26, bold: true, color: COLORS.light },
      isDraft
        ? { text: 'Draft', fontSize: 26, italics: true, color: COLORS.placeholder }
        : {
            text: `#${invoiceId}`, fontSize: 26, bold: true,
            color: options.invoiceUrl ? COLORS.brand : COLORS.black,
            link: options.invoiceUrl,
          },
    ],
  }

  // Right: stacked date rows matching web vertical layout
  const metaRows: Content[] = [
    metaRow('ISSUED', issuedDate),
    metaRow('DUE', dueDate, [0, 4, 0, 0]),
  ]

  if (options.status) {
    metaRows.push(metaRow('STATUS', options.status.toUpperCase(), [0, 4, 0, 0], COLORS.brand))
  }

  return {
    columns: [
      { stack: [titleLine], width: '*' } as Column,
      { stack: metaRows, width: 170, alignment: 'right' } as Column,
    ],
  }
}

function metaRow(
  label: string,
  value: string,
  margin?: [number, number, number, number],
  valueColor?: string
): Content {
  return {
    columns: [
      { text: label, fontSize: 8, bold: true, color: COLORS.light, width: 48, characterSpacing: 1.2 },
      { text: value, fontSize: 10, bold: !!valueColor, color: valueColor ?? COLORS.text, alignment: 'right' as const },
    ],
    ...(margin ? { margin } : {}),
  }
}

// ── Parties (matches PartyInfo.tsx) ─────────────────────────

function buildParties(data: PartialInvoice): ContentColumns {
  return {
    columns: [
      partyColumn('FROM', data.from, 'left'),
      partyColumn('BILL TO', data.client, 'right'),
    ],
    margin: [0, 10, 0, 14] as [number, number, number, number],
  }
}

/** Party detail row with inline SVG icon (matching web PartyInfo Lucide icons) */
function detailRow(
  icon: string,
  text: string,
  align: 'left' | 'right',
  opts?: { fontSize?: number; color?: string; lineHeight?: number; margin?: [number, number, number, number]; link?: string }
): Content {
  const fontSize = opts?.fontSize ?? 9
  const iconTop = fontSize >= 8 ? 1 : 0
  const iconCol = { svg: icon, width: ICON_SIZE, margin: [0, iconTop, 0, 0] } as Column
  const textCol = {
    text,
    fontSize,
    color: opts?.link ? COLORS.text : (opts?.color ?? COLORS.text),
    alignment: align,
    lineHeight: opts?.lineHeight,
    characterSpacing: opts?.fontSize && opts.fontSize < 8 ? 0.2 : undefined,
    link: opts?.link,
    width: '*',
  } as Column

  return {
    columns: align === 'right' ? [textCol, iconCol] : [iconCol, textCol],
    columnGap: 5,
    margin: opts?.margin ?? [0, 3, 0, 0],
  }
}

function partyColumn(
  label: string,
  party: PartialInvoice['from'] | PartialInvoice['client'] | undefined,
  align: 'left' | 'right'
): Column {
  const lines: Content[] = [
    { text: label, fontSize: 8, bold: true, color: COLORS.light, alignment: align, characterSpacing: 1.5 },
  ]

  if (!party?.name) {
    lines.push({
      text: '\u2014',
      fontSize: 14,
      bold: true,
      color: COLORS.placeholder,
      alignment: align,
      margin: [0, 4, 0, 0],
    })
    return { stack: lines, width: '*' } as Column
  }

  // Name — matching web text-lg font-bold mb-3
  lines.push({
    text: party.name,
    fontSize: 14,
    bold: true,
    color: COLORS.black,
    alignment: align,
    margin: [0, 4, 0, 6],
  })

  // Contact details with icons (matching web space-y-2: MailIcon, PhoneIcon, HashIcon)
  if (party.email) {
    lines.push(detailRow(ICONS.mail, party.email, align, { link: `mailto:${party.email}` }))
  }
  if (party.phone) {
    lines.push(detailRow(ICONS.phone, party.phone, align, { link: `tel:${party.phone}` }))
  }
  if (party.taxId) {
    lines.push(detailRow(ICONS.hash, party.taxId, align))
  }

  // Extra top spacing (matching web mt-3 + MapPinIcon)
  if (party.physicalAddress) {
    lines.push(detailRow(ICONS.mapPin, party.physicalAddress, align, {
      color: COLORS.muted,
      lineHeight: 1.5,
      margin: [0, 6, 0, 0],
    }))
  }

  // Matching web mt-3 + WalletIcon
  if (label === 'BILL TO' && party.walletAddress) {
    lines.push(detailRow(ICONS.wallet, party.walletAddress, align, {
      fontSize: 7,
      color: COLORS.zinc600,
      margin: [0, 6, 0, 0],
    }))
  }

  return { stack: lines, width: '*' } as Column
}

// ── Line Items (matches LineItemsTable.tsx) ──────────────────

function buildLineItems(
  items: PartialInvoice['items'],
  decimals: number
): Content {
  const safeItems = (items ?? []) as Array<{ description?: string; quantity?: number; rate?: string }>

  // UPPERCASE headers matching web text-xs font-bold tracking-widest uppercase
  const headerRow = [
    { text: '#', fontSize: 8, bold: true, color: COLORS.black, alignment: 'center' as const, characterSpacing: 1.2 },
    { text: 'DESCRIPTION', fontSize: 8, bold: true, color: COLORS.black, characterSpacing: 1.2 },
    { text: 'QTY', fontSize: 8, bold: true, color: COLORS.black, alignment: 'center' as const, characterSpacing: 1.2 },
    { text: 'RATE (PER UNIT)', fontSize: 8, bold: true, color: COLORS.black, alignment: 'right' as const, characterSpacing: 1.2 },
    { text: 'AMOUNT', fontSize: 8, bold: true, color: COLORS.black, alignment: 'right' as const, characterSpacing: 1.2 },
  ]

  const dataRows: Content[][] = safeItems.map((item, i) => {
    const qty = item.quantity ?? 0
    const rate = item.rate ?? '0'
    const lineTotal = computeLineTotal(qty, rate, decimals)
    // Format quantity with thousand separators matching web toLocaleString
    const formattedQty = qty.toLocaleString('en-US', { maximumFractionDigits: 6, useGrouping: true })
    return [
      { text: `${i + 1}`, alignment: 'center' as const, color: COLORS.zinc600 },
      { text: item.description ?? '', color: COLORS.black },
      { text: formattedQty, alignment: 'center' as const, color: COLORS.textMd },
      { text: formatAmount(rate, decimals), alignment: 'right' as const, color: COLORS.textMd },
      { text: formatAmount(lineTotal, decimals), alignment: 'right' as const, bold: true, color: COLORS.black },
    ]
  })

  if (dataRows.length === 0) {
    dataRows.push([
      { text: 'No line items', colSpan: 5, alignment: 'center' as const, color: COLORS.light, italics: true, fontSize: 9 } as Content,
      { text: '' } as Content,
      { text: '' } as Content,
      { text: '' } as Content,
      { text: '' } as Content,
    ])
  }

  return {
    table: {
      headerRows: 1,
      widths: [24, '*', 50, 95, 95],
      body: [headerRow, ...dataRows],
    },
    layout: {
      // Thick after header (matching border-b-2 border-zinc-700), thin between rows, none at edges
      hLineWidth: (i: number, node: { table: { body: unknown[][] } }) =>
        i === 1 ? 1.5 : (i > 1 && i < node.table.body.length) ? 0.3 : 0,
      vLineWidth: () => 0,
      hLineColor: (i: number) => i === 1 ? COLORS.borderThick : COLORS.borderLight,
      paddingTop: () => 8,
      paddingBottom: () => 8,
      // Zebra striping matching web even:bg-zinc-50/50
      fillColor: (rowIndex: number) => rowIndex > 0 && rowIndex % 2 === 0 ? COLORS.bgLight : null,
    },
  }
}

// ── Bottom Section: Payment Info + Totals (matches PaperTotals.tsx) ──

function buildBottomSection(
  totals: FormattedTotals,
  currency: string,
  data: PartialInvoice,
  networkName: string,
  options: PdfExportOptions
): ContentColumns {
  return {
    columns: [
      buildPaymentInfoCard(data, networkName, currency, options),
      buildTotalsColumn(totals, currency, data.tax, data.discount),
    ],
    margin: [0, 8, 0, 0] as [number, number, number, number],
  }
}

/** Payment Info card — compact key-value list with unified icon + value pattern */
function buildPaymentInfoCard(
  data: PartialInvoice,
  networkName: string,
  currency: string,
  options: PdfExportOptions
): Column {
  const walletAddress = data.from?.walletAddress ?? ''
  const cardContent: Content[] = []

  if (networkName) {
    cardContent.push({
      columns: [
        { svg: ICONS.globe, width: ICON_SIZE, margin: [0, 1, 0, 0] } as Column,
        { text: networkName, fontSize: 9, bold: true, color: COLORS.text },
      ],
      columnGap: 5,
      margin: [0, 0, 0, 5] as [number, number, number, number],
    })
  }

  if (currency) {
    cardContent.push({
      columns: [
        { svg: ICONS.coin, width: ICON_SIZE, margin: [0, 1, 0, 0] } as Column,
        { text: currency, fontSize: 9, bold: true, color: COLORS.text },
      ],
      columnGap: 5,
      margin: [0, 0, 0, data.tokenAddress ? 2 : 5] as [number, number, number, number],
    })
    if (data.tokenAddress) {
      cardContent.push({
        text: data.tokenAddress,
        fontSize: 6.5,
        color: COLORS.zinc600,
        characterSpacing: 0.2,
        margin: [ICON_SIZE + 5, 0, 0, 5],
      } as Content)
    }
  }

  if (walletAddress && cardContent.length > 0) {
    cardContent.push({
      canvas: [{ type: 'line', x1: 0, y1: 0, x2: 200, y2: 0, lineWidth: 0.3, lineColor: COLORS.borderLight }],
      margin: [0, 2, 0, 6],
    } as Content)
  }

  if (walletAddress) {
    cardContent.push({
      columns: [
        { svg: ICONS.wallet, width: ICON_SIZE } as Column,
        { text: walletAddress, fontSize: 6.5, color: COLORS.black, characterSpacing: 0.2 },
      ],
      columnGap: 5,
      margin: [0, 0, 0, 6] as [number, number, number, number],
    })
  }

  // QR Code — only for pending invoices (paid invoices show tx hash instead)
  if (options.invoiceUrl && (!options.status || options.status === 'pending')) {
    cardContent.push({
      stack: [
        { qr: options.invoiceUrl, fit: 120, alignment: 'center' as const, margin: [0, 4, 0, 2] },
        { text: 'SCAN TO PAY', fontSize: 6, bold: true, color: COLORS.light, alignment: 'center' as const, characterSpacing: 0.8 },
      ],
    })
  }

  if (options.txHash) {
    const explorerUrl = data.networkId ? getExplorerUrl(data.networkId, options.txHash) : undefined
    cardContent.push(
      {
        columns: [
          { svg: ICONS.hash, width: ICON_SIZE, margin: [0, 1, 0, 0] } as Column,
          { text: 'Transaction', fontSize: 7.5, bold: true, color: COLORS.muted },
        ],
        columnGap: 3,
        margin: [0, 6, 0, 2],
      } as Content,
      {
        text: options.txHash,
        fontSize: 6,
        color: COLORS.txText,
        characterSpacing: 0.1,
        link: explorerUrl,
      } as Content
    )
  }

  // Fallback
  if (cardContent.length === 0) {
    cardContent.push({ text: 'No payment details', fontSize: 8, color: COLORS.light, italics: true } as Content)
  }

  return {
    table: {
      widths: ['*'],
      body: [
        [{
          text: 'PAYMENT INFO',
          fontSize: 7.5,
          bold: true,
          color: COLORS.muted,
          characterSpacing: 1.2,
          fillColor: COLORS.bgMuted,
          margin: [10, 5, 10, 5],
        }],
        [{
          stack: cardContent,
          fillColor: COLORS.bgLight,
          margin: [10, 10, 10, 10],
        }],
      ],
    },
    layout: {
      hLineWidth: (i: number) => i === 1 ? 0 : 0.5,
      vLineWidth: () => 0.5,
      hLineColor: () => COLORS.borderLight,
      vLineColor: () => COLORS.borderLight,
    },
    width: 240,
  } as Column
}

/** Totals column matching TotalsSection.tsx with violet total */
function buildTotalsColumn(
  totals: FormattedTotals,
  currency: string,
  tax: string | undefined,
  discount: string | undefined
): Column {
  const currencyLabel = currency || 'TOKEN'
  const rows: Content[] = []

  // Subtotal
  rows.push(totalsRow('Subtotal', totals.subtotal, currencyLabel))

  // Tax (red)
  if (tax && tax !== '0') {
    rows.push(totalsRow(`Tax (${tax}%)`, `+${totals.taxAmount}`, currencyLabel, COLORS.taxRed))
  }

  // Discount (green)
  if (discount && discount !== '0') {
    rows.push(totalsRow(`Discount (${discount}%)`, `-${totals.discountAmount}`, currencyLabel, COLORS.discountGreen))
  }

  // Divider matching web border-t border-zinc-200
  rows.push({
    canvas: [{ type: 'line', x1: 0, y1: 0, x2: 220, y2: 0, lineWidth: 0.5, lineColor: COLORS.borderLight }],
    margin: [0, 6, 0, 6],
  })

  // Total — large violet matching web text-2xl font-black text-violet-600
  rows.push({
    columns: [
      { text: 'Total', fontSize: 16, bold: true, color: COLORS.black, width: 'auto', margin: [0, 5, 0, 0] },
      {
        text: [
          { text: `${totals.total}  `, fontSize: 22, bold: true, color: COLORS.brand },
          { text: currencyLabel, fontSize: 11, bold: true, color: COLORS.muted },
        ],
        alignment: 'right' as const,
      },
    ],
    margin: [0, 2, 0, 0] as [number, number, number, number],
  })

  // Magic Dust (matching web MagicDustBadge with FingerprintIcon)
  if (totals.magicDust) {
    rows.push({
      columns: [
        { text: '', width: '*' } as Column,
        { svg: ICONS.fingerprint, width: ICON_SIZE, margin: [0, 1, 0, 0] } as Column,
        {
          text: [
            { text: 'Unique ID: ', fontSize: 8, color: COLORS.muted },
            { text: `${totals.magicDust} ${currencyLabel}`, fontSize: 8, color: COLORS.muted },
          ],
          width: 'auto',
        } as Column,
      ],
      columnGap: 3,
      margin: [0, 4, 0, 0],
    })
  }

  return { stack: rows, width: '*', margin: [24, 0, 0, 0] } as Column
}

function totalsRow(
  label: string,
  amount: string,
  currency: string,
  amountColor?: string
): Content {
  return {
    columns: [
      { text: label, fontSize: 10, color: COLORS.muted, width: '*' },
      { text: amount, fontSize: 10, color: amountColor ?? COLORS.text, alignment: 'right' as const, width: 'auto' },
      { text: currency, fontSize: 10, color: COLORS.muted, width: 'auto', margin: [6, 0, 0, 0] },
    ],
    margin: [0, 3, 0, 3] as [number, number, number, number],
  }
}

